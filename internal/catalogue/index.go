package catalogue

import (
	"bytes"
	"fmt"
	"slices"
	"strings"
)

// Entry is one app in the index.
type Entry struct {
	Name    string
	Aliases []string // other names the app answers to
	SHA256  string   // hex-encoded SHA-256 of the app's source file
	Summary string
}

// Names returns the app's name followed by its aliases.
func (e Entry) Names() []string {
	return append([]string{e.Name}, e.Aliases...)
}

// File returns the app's file name in the catalogue. The stem lists every
// name the app answers to, separated by dots: pomo.pomodoro.ts.
func (e Entry) File() string {
	return strings.Join(e.Names(), ".") + ".ts"
}

// ParseNames splits a file stem such as "pomo.pomodoro" into the app's name
// and its aliases. Dots cannot appear in a name, so the split is unambiguous.
func ParseNames(stem string) (name string, aliases []string, err error) {
	parts := strings.Split(stem, ".")
	for i, n := range parts {
		if err := ValidateName(n); err != nil {
			return "", nil, err
		}
		if slices.Contains(parts[:i], n) {
			return "", nil, fmt.Errorf("name %q is listed twice", n)
		}
	}
	return parts[0], parts[1:], nil
}

// Index maps app names and aliases to the exact bytes that were reviewed.
//
// Format: one tab-separated line per app (names, sha256, summary), where names
// is the app's file stem. Blank lines and lines starting with '#' are ignored.
type Index struct {
	entries []Entry
	byName  map[string]int
}

// ParseIndex parses index.tsv. It is strict: any malformed line is an error,
// so a corrupted or truncated download is never partially trusted.
func ParseIndex(data []byte) (*Index, error) {
	ix := &Index{byName: map[string]int{}}
	for i, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSuffix(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 3 {
			return nil, fmt.Errorf("index line %d: expected 3 tab-separated fields, got %d", i+1, len(fields))
		}
		name, aliases, err := ParseNames(fields[0])
		if err != nil {
			return nil, fmt.Errorf("index line %d: %w", i+1, err)
		}
		e := Entry{Name: name, Aliases: aliases, SHA256: fields[1], Summary: fields[2]}
		if !validSHA256(e.SHA256) {
			return nil, fmt.Errorf("index line %d: invalid sha256 for %q", i+1, e.Name)
		}
		for _, n := range e.Names() {
			if _, dup := ix.byName[Normalize(n)]; dup {
				return nil, fmt.Errorf("index line %d: duplicate app %q", i+1, n)
			}
			ix.byName[Normalize(n)] = len(ix.entries)
		}
		ix.entries = append(ix.entries, e)
	}
	return ix, nil
}

// Lookup returns the entry for name, which may be an alias. Hyphens are
// ignored, so "billionairecharity" finds "billionaire-charity".
func (ix *Index) Lookup(name string) (Entry, bool) {
	i, ok := ix.byName[Normalize(name)]
	if !ok {
		return Entry{}, false
	}
	return ix.entries[i], true
}

// Entries returns all entries in index order.
func (ix *Index) Entries() []Entry {
	return append([]Entry(nil), ix.entries...)
}

// FormatIndex renders entries in the index.tsv format.
func FormatIndex(entries []Entry) []byte {
	var b bytes.Buffer
	b.WriteString("# names\tsha256\tsummary\n")
	b.WriteString("# Generated by quick-catalogue. Do not edit by hand.\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "%s\t%s\t%s\n", strings.Join(e.Names(), "."), e.SHA256, e.Summary)
	}
	return b.Bytes()
}
