package catalogue

import (
	"bytes"
	"fmt"
	"strings"
)

// Entry is one app in the index.
type Entry struct {
	Name    string
	SHA256  string // hex-encoded SHA-256 of the app's source file
	Summary string
}

// Index maps app names to the exact bytes that were reviewed.
//
// Format: one tab-separated line per app (name, sha256, summary). Blank lines
// and lines starting with '#' are ignored.
type Index struct {
	entries []Entry
	byName  map[string]int
}

// ParseIndex parses index.tsv. It is strict: any malformed line is an error,
// so a corrupted or truncated download is never partially trusted.
func ParseIndex(data []byte) (*Index, error) {
	ix := &Index{byName: map[string]int{}}
	for i, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSuffix(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 3 {
			return nil, fmt.Errorf("index line %d: expected 3 tab-separated fields, got %d", i+1, len(fields))
		}
		e := Entry{Name: fields[0], SHA256: fields[1], Summary: fields[2]}
		if err := ValidateName(e.Name); err != nil {
			return nil, fmt.Errorf("index line %d: %w", i+1, err)
		}
		if !validSHA256(e.SHA256) {
			return nil, fmt.Errorf("index line %d: invalid sha256 for %q", i+1, e.Name)
		}
		if _, dup := ix.byName[e.Name]; dup {
			return nil, fmt.Errorf("index line %d: duplicate app %q", i+1, e.Name)
		}
		ix.byName[e.Name] = len(ix.entries)
		ix.entries = append(ix.entries, e)
	}
	return ix, nil
}

// Lookup returns the entry for name.
func (ix *Index) Lookup(name string) (Entry, bool) {
	i, ok := ix.byName[name]
	if !ok {
		return Entry{}, false
	}
	return ix.entries[i], true
}

// Entries returns all entries in index order.
func (ix *Index) Entries() []Entry {
	return append([]Entry(nil), ix.entries...)
}

// FormatIndex renders entries in the index.tsv format.
func FormatIndex(entries []Entry) []byte {
	var b bytes.Buffer
	b.WriteString("# name\tsha256\tsummary\n")
	b.WriteString("# Generated by quick-catalogue. Do not edit by hand.\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "%s\t%s\t%s\n", e.Name, e.SHA256, e.Summary)
	}
	return b.Bytes()
}
