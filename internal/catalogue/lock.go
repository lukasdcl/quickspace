package catalogue

import (
	"bytes"
	"fmt"
	"regexp"
	"slices"
	"strings"
)

// Platforms are the Deno release targets quick supports, named as in Deno's
// release archives (deno-<platform>.zip).
var Platforms = []string{
	"aarch64-apple-darwin",
	"x86_64-apple-darwin",
	"aarch64-unknown-linux-gnu",
	"x86_64-unknown-linux-gnu",
	"aarch64-pc-windows-msvc",
	"x86_64-pc-windows-msvc",
}

var versionPattern = regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`)

// Lock pins the Deno runtime that runs every app.
//
// Format:
//
//	version 2.9.7
//	sha256 <platform> <hex digest of deno-<platform>.zip>
type Lock struct {
	Version string
	SHA256  map[string]string // keyed by platform
}

// ValidateVersion reports whether v looks like a Deno release version.
func ValidateVersion(v string) error {
	if !versionPattern.MatchString(v) {
		return fmt.Errorf("%q is not a version like 2.9.7", v)
	}
	return nil
}

// ParseLock parses runtime.lock strictly.
func ParseLock(data []byte) (*Lock, error) {
	l := &Lock{SHA256: map[string]string{}}
	for i, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSuffix(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Fields(line)
		switch {
		case len(f) == 2 && f[0] == "version":
			if l.Version != "" {
				return nil, fmt.Errorf("runtime.lock line %d: version given twice", i+1)
			}
			if err := ValidateVersion(f[1]); err != nil {
				return nil, fmt.Errorf("runtime.lock line %d: %w", i+1, err)
			}
			l.Version = f[1]
		case len(f) == 3 && f[0] == "sha256":
			if !slices.Contains(Platforms, f[1]) {
				return nil, fmt.Errorf("runtime.lock line %d: unknown platform %q", i+1, f[1])
			}
			if !validSHA256(f[2]) {
				return nil, fmt.Errorf("runtime.lock line %d: invalid sha256", i+1)
			}
			if _, dup := l.SHA256[f[1]]; dup {
				return nil, fmt.Errorf("runtime.lock line %d: duplicate platform %q", i+1, f[1])
			}
			l.SHA256[f[1]] = f[2]
		default:
			return nil, fmt.Errorf("runtime.lock line %d: unrecognised entry", i+1)
		}
	}
	if l.Version == "" {
		return nil, fmt.Errorf("runtime.lock: no version")
	}
	return l, nil
}

// Format renders the lock in the runtime.lock format, platforms in the
// order of Platforms.
func (l *Lock) Format() []byte {
	var b bytes.Buffer
	b.WriteString("# Deno runtime used by every quick app.\n")
	b.WriteString("# Generated by quick-catalogue. Do not edit by hand.\n")
	fmt.Fprintf(&b, "version %s\n", l.Version)
	for _, p := range Platforms {
		if sum, ok := l.SHA256[p]; ok {
			fmt.Fprintf(&b, "sha256 %s %s\n", p, sum)
		}
	}
	return b.Bytes()
}
